import { useMutation } from "@tanstack/react-query";
import { Bot, Database, Send } from "lucide-react";
import { useState } from "react";
import { api } from "../lib/api";

type Evidence = { id: string; category: string; text: string; source: string };
type Answer = {
  id: string; answer: string; kind: string; evidence: Evidence[];
  provider: "deterministic" | "openai"; model: string; generatedAt: string;
};

const examples = [
  "Why is this captain recommended?",
  "Why is the top transfer worth its hit?",
  "What changed since the previous snapshot?",
  "Build a conservative three-week plan.",
  "What evidence would change this recommendation?",
];

export function AdvisorPage() {
  const [question, setQuestion] = useState("");
  const [useLanguageModel, setUseLanguageModel] = useState(false);
  const ask = useMutation({
    mutationFn: (value: string) => api<Answer>("/advisor/ask", {
      method: "POST", body: JSON.stringify({ question: value, useLanguageModel })
    })
  });

  function submit(value: string) {
    const cleaned = value.trim();
    if (cleaned.length >= 3) {
      setQuestion(cleaned);
      ask.mutate(cleaned);
    }
  }

  return <div className="mx-auto max-w-4xl space-y-6">
    <header className="rounded-3xl border border-edge/20 bg-gradient-to-br from-edge/10 to-panel p-7">
      <div className="flex gap-4"><Bot className="text-edge" size={34} /><div>
        <p className="text-xs font-bold uppercase tracking-[.2em] text-edge">Grounded advisor</p>
        <h1 className="mt-2 text-3xl font-black">Ask about the engine’s evidence.</h1>
        <p className="mt-2 text-slate-400">Answers can only use immutable recommendation snapshots, current fixture forecasts, and bounded planner output. The advisor cannot place official FPL actions.</p>
      </div></div>
    </header>

    <form className="card p-5" onSubmit={event => { event.preventDefault(); submit(question); }}>
      <label className="text-sm font-bold" htmlFor="advisor-question">Question</label>
      <div className="mt-2 flex gap-2">
        <textarea id="advisor-question" className="field min-h-24 flex-1 resize-y" maxLength={500} value={question} onChange={event => setQuestion(event.target.value)} placeholder="Why is this captain recommended?" />
        <button className="button-primary self-end" disabled={ask.isPending || question.trim().length < 3}><Send size={17} />{ask.isPending ? "Checking evidence…" : "Ask"}</button>
      </div>
      <label className="mt-3 flex items-start gap-2 text-xs text-slate-400">
        <input type="checkbox" checked={useLanguageModel} onChange={event => setUseLanguageModel(event.target.checked)} />
        <span>Use OpenAI to rank the evidence. Your question and current evidence bundle will be sent to OpenAI when the server has an API key; factual answer text still comes only from FPL Edge.</span>
      </label>
      <div className="mt-3 flex flex-wrap gap-2">{examples.map(example => <button type="button" key={example} className="rounded-full bg-white/5 px-3 py-1.5 text-xs text-slate-400 hover:text-white" onClick={() => submit(example)}>{example}</button>)}</div>
    </form>

    {ask.error && <div className="card border-red-400/20 p-5 text-red-200">{ask.error.message}</div>}
    {ask.data && <section className="space-y-4">
      <article className="card border-edge/20 p-6">
        <div className="mb-4 flex flex-wrap items-center justify-between gap-2"><h2 className="text-xl font-black">Answer</h2><span className="text-xs text-slate-500">{ask.data.provider === "openai" ? "OpenAI evidence ranking" : "Deterministic evidence ranking"} · {ask.data.model}</span></div>
        <p className="leading-8 text-slate-200">{ask.data.answer}</p>
      </article>
      <div><h2 className="mb-3 flex items-center gap-2 text-lg font-black"><Database size={18} className="text-edge" />Evidence used</h2>
        <div className="space-y-2">{ask.data.evidence.map(item => <article className="card p-4" key={item.id}>
          <div className="flex flex-wrap justify-between gap-2"><span className="text-xs font-bold text-edge">[{item.id}] · {item.category}</span><span className="max-w-lg truncate text-[10px] text-slate-600" title={item.source}>{item.source}</span></div>
          <p className="mt-2 text-sm text-slate-300">{item.text}</p>
        </article>)}</div>
      </div>
    </section>}
    <footer className="text-xs leading-6 text-slate-500">The optional language model ranks existing evidence IDs only. Final factual sentences are generated by FPL Edge from stored engine output, so unsupported model prose is never shown.</footer>
  </div>;
}
